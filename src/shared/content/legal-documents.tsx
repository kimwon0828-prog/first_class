// 웹과 앱 API가 같은 문구를 읽는다. p/li만 사용해 native legalBlocks 계약을 유지한다.
const publicText = (text: string) => text
  .replaceAll("{{supportEmail}}", COMPANY_INFO.customerCenterEmail)
  .replaceAll("{{supportPhone}}", COMPANY_INFO.customerCenterPhone)
  .replaceAll("{{representative}}", COMPANY_INFO.representative)

const content = (blocks: readonly { kind: "paragraph" | "bullet"; text: string }[]): ReactNode => {
  const nodes: ReactNode[] = []
  let items: ReactNode[] = []
  const flushList = () => {
    if (items.length === 0) return
    nodes.push(createElement("ul", { key: `list-${nodes.length}` }, items))
    items = []
  }
  blocks.forEach((block, index) => {
    if (block.kind === "bullet") {
      items.push(createElement("li", { key: index }, publicText(block.text)))
    } else {
      flushList()
      nodes.push(createElement("p", { key: `paragraph-${index}` }, publicText(block.text)))
    }
  })
  flushList()
  return nodes
}

